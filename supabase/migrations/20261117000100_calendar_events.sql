on conflict (event_category_id) do update
set category_name = excluded.category_name;

do $$
declare
  category_sequence text;
begin
  category_sequence := pg_get_serial_sequence(
    'public."Event_Category"',
    'event_category_id'
  );
  if category_sequence is not null then
    perform setval(
      category_sequence,
      (select greatest(coalesce(max(event_category_id), 1), 1) from public."Event_Category"),
      true
    );
  end if;
end;
$$;

